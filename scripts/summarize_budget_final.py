"""Collect the final Part B numbers (after run_budget_final.sh) into results/budget/final_summary.md.

1. Certified configurations per study (selected on validation, evaluated once on test):
   ratio order / original ladders, ratio order / extended ladders (control),
   compatibility order / extended ladders.
2. Recall above the static frontier of fixed budgets at equal mean time, from the same
   log file as the configuration (offline times are compared within a file only).
3. Live benchmark (same pairs, same process): full budget vs ratio-order vs
   compatibility-order adaptive budgets, with scene-stratified bootstrap CIs.
4. Original configuration: pre-fix vs corrected accounting.

Usage: python -I scripts/summarize_budget_final.py
"""

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze_budget as B  # noqa: E402

from acpr import RESULTS_ROOT  # noqa: E402
from acpr import analysis as A  # noqa: E402

R = RESULTS_ROOT / "budget"
STUDIES = [("ratio order, original ladders", "budget", "ladder_selection.json"),
           ("ratio order, extended ladders (control)", "budget", "ladder_selection_ext.json"),
           ("compatibility order, extended ladders", "budgetc", "ladder_selection_compat_ext.json")]
SETS = ["3DMatch", "3DLoMatch"]
ESTS = [("sc2", "SC²-PCR"), ("turbo", "TurboReg")]


def hull_value(points, t):
    pts = sorted([(0.0, 0.0)] + points)
    h = []
    for p in pts:
        while len(h) >= 2 and (h[-1][1] - h[-2][1]) * (p[0] - h[-2][0]) <= (p[1] - h[-2][1]) * (h[-1][0] - h[-2][0]):
            h.pop()
        h.append(p)
    xs, ys = zip(*h)
    return float(np.interp(t, xs, ys))


def fixed_points(recs, est):
    pts = []
    for k in range(5):
        o = A.fixed_stage([B.trajectory_ladder(r, est, (k,)) for r in recs], 0)
        pts.append((float(o.s.mean()), float(o.ok.mean())))
    return pts


def fmt_p(p):
    return f"{p:.2g}" if p >= 1e-3 else f"{p:.1e}"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    L = ["# Part B: final numbers (corrected accounting)\n",
         "Generated by `scripts/summarize_budget_final.py` from the outputs of `scripts/run_budget_final.sh`.\n"]
    logs = {pf: {s: B.load(s, pf) for s in SETS} for pf in ("budget", "budgetc")}
    fixed = {(pf, est, s): fixed_points(logs[pf][s], est) for pf in logs for est, _ in ESTS for s in SETS}

    L.append("\n## 1. Certified configurations, test sets (offline)\n")
    L.append("| Study | Estimator | Certificate | Ladder | Test set | RR adaptive vs full | ΔRR [95 % UB of loss], p | "
             "Speed-up vs full [95 % CI] | Risk | vs static frontier |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    for title, pf, fn in STUDIES:
        sel = json.loads((R / fn).read_text())
        for est, en in ESTS:
            for tag in ("mondrian", "marginal"):
                cfg = sel[est]["selected"][tag]
                for s in SETS:
                    t = sel[est]["test"][s][tag]
                    full = sel[est]["test"][s]["full"]
                    fr = hull_value(fixed[(pf, est, s)], t["s"])
                    L.append(f"| {title} | {en} | {'group-conditional' if tag == 'mondrian' else 'marginal'} | "
                             f"`{cfg['ladder']}` | {s} | {100 * t['rr']:.1f} vs {100 * full['rr']:.1f} % | "
                             f"{-100 * t['delta_rr']:+.1f} pp [{100 * t['ub95']:.1f}], p = {fmt_p(t['mcnemar_p'])} | "
                             f"{t['speedup']:.2f}× [{t['speedup_ci'][0]:.2f}, {t['speedup_ci'][1]:.2f}] | "
                             f"{100 * t['risk']:.2f} % | {100 * (t['rr'] - fr):+.1f} pp |")

    L.append("\n## 2. Fixed budgets (single runs), test sets\n")
    L.append("| Order | Estimator | Test set | N=250 | N=500 | N=1000 | N=2000 | N=4000 (full) |")
    L.append("|---|---|---|---|---|---|---|---|")
    for pf, name in (("budget", "ratio"), ("budgetc", "compatibility")):
        for est, en in ESTS:
            for s in SETS:
                pts = fixed[(pf, est, s)]
                L.append(f"| {name} | {en} | {s} | " + " | ".join(f"{100 * rr:.1f} % / {1e3 * t:.0f} ms" for t, rr in pts) + " |")

    live_path = R / "live_budget_compare_ext.json"
    if live_path.exists():
        rows = json.loads(live_path.read_text())
        L.append("\n## 3. Live benchmark (single process, same pairs; group-conditional configurations, extended ladders)\n")
        L.append("| Estimator | Test set | n | Full budget | Adaptive, ratio order | Adaptive, compatibility order | "
                 "Compatibility vs ratio (time) | Live/offline stop agreement (ratio / compat) |")
        L.append("|---|---|---|---|---|---|---|---|")
        for est, en in ESTS:
            for s in SETS:
                rs = [r for r in rows if r["est"] == est and r["subset"] == s]
                if not rs:
                    continue
                sc = np.array([r["scene"] for r in rs])
                tf = np.array([r["full"]["s"] for r in rs])
                cells = [f"{1e3 * tf.mean():.0f} ms, RR {100 * np.mean([r['full']['ok'] for r in rs]):.0f} %"]
                tt = {}
                for pf in ("budget", "budgetc"):
                    ta = np.array([r[pf]["s"] for r in rs])
                    tt[pf] = ta
                    bs = A.stratified_bootstrap(lambda i: tf[i].mean() / ta[i].mean(), sc, B=2000, seed=1)
                    cells.append(f"{1e3 * ta.mean():.0f} ms, RR {100 * np.mean([r[pf]['ok'] for r in rs]):.0f} %, "
                                 f"**{tf.mean() / ta.mean():.2f}×** [{np.quantile(bs, .025):.2f}, {np.quantile(bs, .975):.2f}]")
                bs = A.stratified_bootstrap(lambda i: tt["budget"][i].mean() / tt["budgetc"][i].mean(), sc, B=2000, seed=2)
                a = np.array([r["budgetc"]["ok"] for r in rs])
                b = np.array([r["budget"]["ok"] for r in rs])
                cells.append(f"{tt['budget'].mean() / tt['budgetc'].mean():.2f}× [{np.quantile(bs, .025):.2f}, "
                             f"{np.quantile(bs, .975):.2f}], RR {100 * (a.mean() - b.mean()):+.0f} pp")
                ag = [np.mean([r[pf]["stop"] == r[pf]["offline_stop"] for r in rs]) for pf in ("budget", "budgetc")]
                cells.append(f"{100 * ag[0]:.0f} % / {100 * ag[1]:.0f} %")
                L.append(f"| {en} | {s} | {len(rs)} | " + " | ".join(cells) + " |")

    pre = R / "pre_fix" / "ladder_selection.json"
    if pre.exists():
        a, b = json.loads(pre.read_text()), json.loads((R / "ladder_selection.json").read_text())
        L.append("\n## 4. Original configuration (ratio order): pre-fix vs corrected accounting\n")
        L.append("| Estimator | Certificate | Ladder (pre-fix → corrected) | Test set | Speed-up pre-fix | Speed-up corrected | "
                 "RR pre-fix → corrected | Risk pre-fix → corrected |")
        L.append("|---|---|---|---|---|---|---|---|")
        for est, en in ESTS:
            for tag in ("mondrian", "marginal"):
                la, lb = a[est]["selected"][tag]["ladder"], b[est]["selected"][tag]["ladder"]
                for s in SETS:
                    ta, tb = a[est]["test"][s][tag], b[est]["test"][s][tag]
                    L.append(f"| {en} | {tag} | `{la}` → `{lb}` | {s} | {ta['speedup']:.2f}× | {tb['speedup']:.2f}× | "
                             f"{100 * ta['rr']:.1f} → {100 * tb['rr']:.1f} % | {100 * ta['risk']:.2f} → {100 * tb['risk']:.2f} % |")
    out = R / "final_summary.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
